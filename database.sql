CREATE TABLE IF NOT EXISTS properties (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(180) NOT NULL, slug VARCHAR(190) NOT NULL UNIQUE,
 category VARCHAR(80) NOT NULL DEFAULT 'Residence', location VARCHAR(120) NOT NULL, district VARCHAR(80) NOT NULL,
 price_label VARCHAR(100) NOT NULL, price_lkr DECIMAL(15,2) NULL, bedrooms TINYINT UNSIGNED NOT NULL DEFAULT 0,
 bathrooms TINYINT UNSIGNED NOT NULL DEFAULT 0, area_sqft INT UNSIGNED NOT NULL DEFAULT 0,
 image_url VARCHAR(500) NOT NULL, gallery_json LONGTEXT NULL, excerpt VARCHAR(500) NOT NULL,
 description LONGTEXT NOT NULL, features_json LONGTEXT NULL, is_featured TINYINT(1) NOT NULL DEFAULT 0,
 is_published TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS articles (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(220) NOT NULL, slug VARCHAR(230) NOT NULL UNIQUE,
 category VARCHAR(100) NOT NULL DEFAULT 'Living well', excerpt VARCHAR(500) NOT NULL,
 body LONGTEXT NOT NULL, image_url VARCHAR(500) NOT NULL, is_published TINYINT(1) NOT NULL DEFAULT 1,
 published_at DATETIME NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS inquiries (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(150) NOT NULL, email VARCHAR(190) NOT NULL,
 phone VARCHAR(60) NOT NULL DEFAULT '', interest VARCHAR(100) NOT NULL DEFAULT '', message TEXT NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'New', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS admins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 setting_key VARCHAR(100) PRIMARY KEY, setting_value LONGTEXT NOT NULL
) ENGINE=InnoDB;
